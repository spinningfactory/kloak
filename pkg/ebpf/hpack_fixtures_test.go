var updateFixtures = flag.Bool("update", false, "rewrite "+hpackTailFixtures)

// hpackTailFixtures holds the HPACK-Huffman vectors of helpers_test.c's
// patch_delta tests. TestHPACKTailFixtures checks that it is what Go's hpack
// and huffmanEntry give today; regenerate it with
//
//	go test ./pkg/ebpf/ -run TestHPACKTailFixtures -update
const hpackTailFixtures = "bpf/hpack_tail_fixtures.h"

// hpackTailPairs are (real, shadow) pairs from the shadow generator, so each
// shadow has its real's length and HPACK Huffman bit length. The first eight
// cover every bit length mod 8; the last three have a code of exactly 8
// bytes, a BPF key.
var hpackTailPairs = []struct{ real, shadow string }{
	{"ghp-real-token-10", "kl::Uow2eoiso1ci1"},   // 96 bits: pad 0
	{"ghp-real-token-133", "kl::Ts&81c1t2oii01"}, // 103 bits: pad 1
	{"ghp-real-token-103", "kl::XccFsittesii2s"}, // 102 bits: pad 2
	{"ghp-real-token-100", "kl::7Xeiicoo02ii0o"}, // 101 bits: pad 3
	{"ghp-real-token-3", "kl::rR0d0o922a21"},     // 92 bits: pad 4
	{"ghp-real-token-0", "kl::0R6cc91aa2tt"},     // 91 bits: pad 5
	{"ghp-real-token-33", "kl::LB42smi0co1ic"},   // 98 bits: pad 6
	{"ghp-real-token-13", "kl::0*0sncop0ocs0"},   // 97 bits: pad 7
	{"MFXMWKRIH", "kl::,XGkQ"},                   // 64 bits: pad 0
	{"TH0XCYQTI", "kl::ip&;;"},                   // 62 bits: pad 2
	{"Q5H9-JJ_E", "kl::GKsi&"},                   // 59 bits: pad 5
}

// The text around the placeholder in a header value. The prescan matches a
// Huffman placeholder only on a byte boundary, so a prefix's code must be a
// whole number of bytes ("Bearer " is 40 bits).
var (
	hpackTailPrefixes = []string{"", "Bearer "}
	hpackTailSuffixes = []string{"", "0", "a; b=c", "&x=1", ";tail"}
)

func TestHPACKTailFixtures(t *testing.T) {
	got := renderHPACKTailFixtures(t)
	if *updateFixtures {
		if err := os.WriteFile(hpackTailFixtures, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(hpackTailFixtures)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is out of date: go test ./pkg/ebpf/ -run TestHPACKTailFixtures -update", hpackTailFixtures)
	}
}

// renderHPACKTailFixtures renders hpackTailFixtures: the entry huffmanEntry
// gives each pair, and each header value prefix + shadow + suffix as Go's
// hpack encodes it (wire) and as it must arrive (want, with the real).
func renderHPACKTailFixtures(t *testing.T) []byte {
	t.Helper()
	type tcase struct {
		entry          int
		prefix, suffix string
		offset         int
		wire, want     []byte
	}
	var cases []tcase
	maxLen := 0
	for i, p := range hpackTailPairs {
		for _, prefix := range hpackTailPrefixes {
			if secrets.HuffmanBits(prefix)%8 != 0 {
				t.Fatalf("prefix %q does not end on a byte boundary", prefix)
			}
			for _, suffix := range hpackTailSuffixes {
				c := tcase{
					entry: i, prefix: prefix, suffix: suffix,
					offset: secrets.HuffmanBits(prefix) / 8,
					wire:   hpack.AppendHuffmanString(nil, prefix+p.shadow+suffix),
					want:   hpack.AppendHuffmanString(nil, prefix+p.real+suffix),
				}
				if len(c.wire) != len(c.want) {
					t.Fatalf("%q: wire and want differ in length", p.shadow)
				}
				maxLen = max(maxLen, len(c.wire))
				cases = append(cases, c)
			}
		}
	}

	var b strings.Builder
	b.WriteString(`// hpack_tail_fixtures.h — HPACK-Huffman placeholders for helpers_test.c.
// Generated by TestHPACKTailFixtures (pkg/ebpf/hpack_fixtures_test.go) from
// golang.org/x/net/http2/hpack and the secret_map entries sync stores for
// them (huffmanEntry). Do not edit; regenerate with
//   go test ./pkg/ebpf/ -run TestHPACKTailFixtures -update

#ifndef KLOAK_HPACK_TAIL_FIXTURES_H
#define KLOAK_HPACK_TAIL_FIXTURES_H

`)
	fmt.Fprintf(&b, "#define HPACK_TAIL_MAX %d\n\n", (maxLen+7)/8*8)
	b.WriteString(`// The secret_map entry of the Huffman form of each placeholder.
struct hpack_tail_entry {
  const char *real, *shadow;
  unsigned char key[8];
  __u32 len;
  __u8 pad_bits;
  unsigned char real_secret[HPACK_TAIL_MAX];
};

static const struct hpack_tail_entry hpack_tail_entries[] = {
`)
	for _, p := range hpackTailPairs {
		key, val, err := huffmanEntry(p.shadow, p.real, &secretValue{})
		if err != nil {
			t.Fatalf("%q: %v", p.shadow, err)
		}
		fmt.Fprintf(&b, "  {%q, %q,\n", p.real, p.shadow)
		fmt.Fprintf(&b, "   %s,\n", cBytes(key.Prefix[:], "   "))
		fmt.Fprintf(&b, "   %d, %d,\n", val.Len, val.PadBits)
		fmt.Fprintf(&b, "   %s},\n", cBytes(val.RealSecret[:val.Len], "   "))
	}
	b.WriteString(`};

// A header value prefix + placeholder + suffix, as Huffman(prefix + shadow +
// suffix) on the wire, and as Huffman(prefix + real + suffix) once patched.
struct hpack_tail_case {
  int entry; // in hpack_tail_entries
  const char *prefix, *suffix;
  __u32 offset; // of the placeholder's code
  __u32 len;    // of wire and want
  unsigned char wire[HPACK_TAIL_MAX];
  unsigned char want[HPACK_TAIL_MAX];
};

static const struct hpack_tail_case hpack_tail_cases[] = {
`)
	for _, c := range cases {
		fmt.Fprintf(&b, "  {%d, %q, %q, %d, %d,\n", c.entry, c.prefix, c.suffix, c.offset, len(c.wire))
		fmt.Fprintf(&b, "   %s,\n", cBytes(c.wire, "   "))
		fmt.Fprintf(&b, "   %s},\n", cBytes(c.want, "   "))
	}
	b.WriteString("};\n\n#endif // KLOAK_HPACK_TAIL_FIXTURES_H\n")
	return []byte(b.String())
}

// cBytes renders b as a C array initializer, 12 bytes a line.
func cBytes(b []byte, indent string) string {
	var s strings.Builder
	s.WriteString("{")
	for i, c := range b {
		switch {
		case i == 0:
		case i%12 == 0:
			s.WriteString(",\n" + indent + " ")
		default:
			s.WriteString(", ")
		}
		fmt.Fprintf(&s, "0x%02x", c)
	}
	s.WriteString("}")
	return s.String()
}
